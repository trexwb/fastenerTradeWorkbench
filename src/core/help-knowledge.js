/** 帮助检索：按关键词匹配标题/关键词/正文，返回最多 3 条（每条截断 1200 字符） */
function helpSearch(keyword){
  const kw=String(keyword||'').trim().toLowerCase();
  if(!kw)return JSON.stringify({ok:true,count:0,items:[],hint:'请输入关键词，如：订单、寻货、报价、回收站、备份'});
  const scored=[];
  HELP_KNOWLEDGE.forEach(function(topic){
    const titleHit=(topic.title||'').toLowerCase().includes(kw);
    const kwHit=(topic.keywords||[]).some(function(k){return k.toLowerCase().includes(kw)||kw.includes(k.toLowerCase());});
    const bodyHit=(topic.content||'').toLowerCase().includes(kw);
    let score=0;
    if(titleHit)score+=3;
    if(kwHit)score+=2;
    if(bodyHit)score+=1;
    if(score>0){
      scored.push({key:topic.key,title:topic.title,score:score,content:topic.content});
    }
  });
  scored.sort(function(a,b){return b.score-a.score;});
  const items=scored.slice(0,3).map(function(t){
    return {key:t.key,title:t.title,content:t.content.length>1200?t.content.slice(0,1200)+'…':t.content};
  });
  return JSON.stringify({ok:true,count:items.length,items:items});
}
